-- 3-2 FINANCIAL（商品相關，共 4 支）
-- 用途：依會員查詢商品
CREATE OR ALTER PROCEDURE FINANCIAL.GET_PRODUCTS
    @USER_ID CHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT
        NO,
        USER_ID,
        PRODUCT_NAME,
        PRICE,
        FEE_RATE
    FROM FINANCIAL.PRODUCT
    WHERE USER_ID = @USER_ID
    ORDER BY PRICE DESC, NO DESC;
END;
GO
-- 用途：建立金融商品
CREATE OR ALTER PROCEDURE FINANCIAL.INSERT_PRODUCT
    @USER_ID       CHAR(10),
    @PRODUCT_NAME  NVARCHAR(50),
    @PRICE         DECIMAL(12,2),
    @FEE_RATE      DECIMAL(10,6)
AS
BEGIN
    SET NOCOUNT ON;
    IF @PRODUCT_NAME IS NULL OR LEN(LTRIM(RTRIM(@PRODUCT_NAME))) = 0
        THROW 50031, N'請輸入商品名稱', 1;
    IF @PRICE IS NULL OR @PRICE < 0.01 OR @PRICE > 99999999.99
        THROW 50032, N'價格須介於 0.01～99,999,999.99', 1;
    IF @FEE_RATE IS NULL OR @FEE_RATE < 0 OR @FEE_RATE > 1
        THROW 50033, N'手續費率須介於 0～100%', 1;
    INSERT INTO FINANCIAL.PRODUCT (
        USER_ID, PRODUCT_NAME, PRICE, FEE_RATE
    ) VALUES (
        @USER_ID, @PRODUCT_NAME, @PRICE, @FEE_RATE
    );
END;
GO
-- 用途：更新商品資料，並於重算喜好清單的手續費與總金額
CREATE OR ALTER PROCEDURE FINANCIAL.UPDATE_PRODUCT
    @NO            INT,
    @USER_ID       CHAR(10),
    @PRODUCT_NAME  NVARCHAR(50),
    @PRICE         DECIMAL(12,2),
    @FEE_RATE      DECIMAL(10,6)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @PRODUCT_NAME IS NULL OR LEN(LTRIM(RTRIM(@PRODUCT_NAME))) = 0
        THROW 50031, N'請輸入商品名稱', 1;
    IF @PRICE IS NULL OR @PRICE < 0.01 OR @PRICE > 99999999.99
        THROW 50032, N'價格須介於 0.01～99,999,999.99', 1;
    IF @FEE_RATE IS NULL OR @FEE_RATE < 0 OR @FEE_RATE > 1
        THROW 50033, N'手續費率須介於 0～100%', 1;
    BEGIN TRY
        BEGIN TRANSACTION;
        UPDATE FINANCIAL.PRODUCT
        SET PRODUCT_NAME = @PRODUCT_NAME,
            PRICE = @PRICE,
            FEE_RATE = @FEE_RATE
        WHERE NO = @NO AND USER_ID = @USER_ID;
        IF @@ROWCOUNT = 0
            THROW 50027, N'找不到指定商品', 1;
        IF EXISTS (
            SELECT 1
            FROM FAVORITE.LIKE_LIST L
            WHERE L.PRODUCT_NO = @NO
              AND (
                  TRY_CONVERT(DECIMAL(12,2),
                      ROUND(@PRICE * L.PURCHASE_QUANTITY * @FEE_RATE, 2)
                  ) IS NULL
                  OR TRY_CONVERT(DECIMAL(14,2),
                      ROUND(@PRICE * L.PURCHASE_QUANTITY * (1 + @FEE_RATE), 2)
                  ) IS NULL
              )
        )
            THROW 50026, N'計算金額超出允許範圍', 1;
        UPDATE L
        SET TOTAL_FEE = ROUND(
                @PRICE * L.PURCHASE_QUANTITY * @FEE_RATE, 2
            ),
            TOTAL_AMOUNT = ROUND(
                @PRICE * L.PURCHASE_QUANTITY * (1 + @FEE_RATE), 2
            )
        FROM FAVORITE.LIKE_LIST L
        WHERE L.PRODUCT_NO = @NO;
        COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;
        THROW;
    END CATCH;
END;
GO
-- 用途：刪除會員的商品
CREATE OR ALTER PROCEDURE FINANCIAL.DELETE_PRODUCT
    @NO INT,
    @USER_ID CHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF NOT EXISTS (
        SELECT 1 FROM FINANCIAL.PRODUCT
        WHERE NO = @NO AND USER_ID = @USER_ID
    )
        THROW 50027, N'找不到指定商品', 1;
    IF EXISTS (
        SELECT 1 FROM FAVORITE.LIKE_LIST
        WHERE PRODUCT_NO = @NO
    )
        THROW 50028, N'此商品已加入喜好清單，請先移除喜好紀錄', 1;
    DELETE FROM FINANCIAL.PRODUCT
    WHERE NO = @NO AND USER_ID = @USER_ID;
    IF @@ROWCOUNT = 0
        THROW 50027, N'找不到指定商品', 1;
END;
GO
-- 3-3 FAVORITE（喜好清單相關，共 4 支）
-- 用途：JOIN 喜好、商品與會員資料
CREATE OR ALTER PROCEDURE FAVORITE.GET_LIKES
    @USER_ID CHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT
        L.SN AS sn,
        L.PRODUCT_NO AS productNo,
        P.PRODUCT_NAME AS productName,
        P.PRICE AS price,
        P.FEE_RATE AS feeRate,
        L.PURCHASE_QUANTITY AS purchaseQuantity,
        L.ACCOUNT AS account,
        L.TOTAL_FEE AS totalFee,
        L.TOTAL_AMOUNT AS totalAmount,
        U.EMAIL AS email
    FROM FAVORITE.LIKE_LIST L
    JOIN FINANCIAL.PRODUCT P ON P.NO = L.PRODUCT_NO
    JOIN MEMBER.USER_ACCOUNT U ON U.USER_ID = P.USER_ID
    WHERE P.USER_ID = @USER_ID
    ORDER BY L.TOTAL_AMOUNT DESC, L.SN DESC;
END;
GO
-- 用途：驗證數量、帳號、商品歸屬及重複資料，計算手續費與預計扣款金額。
CREATE OR ALTER PROCEDURE FAVORITE.INSERT_LIKE
    @USER_ID CHAR(10),
    @PRODUCT_NO INT,
    @PURCHASE_QUANTITY INT,
    @ACCOUNT VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @PURCHASE_QUANTITY IS NULL OR @PURCHASE_QUANTITY <= 0
        THROW 50021, N'購買數量必須大於 0', 1;
    IF @ACCOUNT IS NULL
       OR LEN(@ACCOUNT) NOT BETWEEN 10 AND 16
       OR @ACCOUNT LIKE '%[^0-9]%'
        THROW 50022, N'扣款帳號須為 10～16 碼數字', 1;
    IF NOT EXISTS (
        SELECT 1
        FROM FINANCIAL.PRODUCT
        WHERE NO = @PRODUCT_NO
          AND USER_ID = @USER_ID
    )
        THROW 50023, N'找不到指定商品', 1;
    IF EXISTS (
        SELECT 1
        FROM FAVORITE.LIKE_LIST
        WHERE PRODUCT_NO = @PRODUCT_NO
    )
        THROW 50025, N'此商品已加入喜好清單', 1;
    IF EXISTS (
        SELECT 1
        FROM FINANCIAL.PRODUCT
        WHERE NO = @PRODUCT_NO
          AND USER_ID = @USER_ID
          AND (
              TRY_CONVERT(DECIMAL(12,2),
                  ROUND(PRICE * @PURCHASE_QUANTITY * FEE_RATE, 2)
              ) IS NULL
              OR TRY_CONVERT(DECIMAL(14,2),
                  ROUND(PRICE * @PURCHASE_QUANTITY * (1 + FEE_RATE), 2)
              ) IS NULL
          )
    )
        THROW 50026, N'計算金額超出允許範圍', 1;
    INSERT INTO FAVORITE.LIKE_LIST (
        PRODUCT_NO,
        PURCHASE_QUANTITY,
        ACCOUNT,
        TOTAL_FEE,
        TOTAL_AMOUNT
    )
    SELECT
        NO,
        @PURCHASE_QUANTITY,
        @ACCOUNT,
        ROUND(PRICE * @PURCHASE_QUANTITY * FEE_RATE, 2),
        ROUND(PRICE * @PURCHASE_QUANTITY * (1 + FEE_RATE), 2)
    FROM FINANCIAL.PRODUCT
    WHERE NO = @PRODUCT_NO
      AND USER_ID = @USER_ID;
END;
GO
-- 用途：驗證紀錄歸屬及商品，更新數量、帳號並重新計算金額。
CREATE OR ALTER PROCEDURE FAVORITE.UPDATE_LIKE
    @SN INT,
    @USER_ID CHAR(10),
    @PRODUCT_NO INT,
    @PURCHASE_QUANTITY INT,
    @ACCOUNT VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    IF @PURCHASE_QUANTITY IS NULL OR @PURCHASE_QUANTITY <= 0
        THROW 50021, N'購買數量必須大於 0', 1;
    IF @ACCOUNT IS NULL
       OR LEN(@ACCOUNT) NOT BETWEEN 10 AND 16
       OR @ACCOUNT LIKE '%[^0-9]%'
        THROW 50022, N'扣款帳號須為 10～16 碼數字', 1;
    IF NOT EXISTS (
        SELECT 1
        FROM FAVORITE.LIKE_LIST L
        JOIN FINANCIAL.PRODUCT OLD_P ON OLD_P.NO = L.PRODUCT_NO
        WHERE L.SN = @SN AND OLD_P.USER_ID = @USER_ID
    )
        THROW 50024, N'找不到喜好紀錄', 1;
    IF NOT EXISTS (
        SELECT 1 FROM FINANCIAL.PRODUCT
        WHERE NO = @PRODUCT_NO AND USER_ID = @USER_ID
    )
        THROW 50023, N'找不到指定商品', 1;
    IF EXISTS (
        SELECT 1 FROM FAVORITE.LIKE_LIST
        WHERE PRODUCT_NO = @PRODUCT_NO AND SN <> @SN
    )
        THROW 50025, N'此商品已加入喜好清單', 1;
    IF EXISTS (
        SELECT 1 FROM FINANCIAL.PRODUCT P
        WHERE P.NO = @PRODUCT_NO AND P.USER_ID = @USER_ID
          AND (
              TRY_CONVERT(DECIMAL(12,2),
                  ROUND(P.PRICE * @PURCHASE_QUANTITY * P.FEE_RATE, 2)
              ) IS NULL
              OR TRY_CONVERT(DECIMAL(14,2),
                  ROUND(P.PRICE * @PURCHASE_QUANTITY * (1 + P.FEE_RATE), 2)
              ) IS NULL
          )
    )
        THROW 50026, N'計算金額超出允許範圍', 1;
    UPDATE L
    SET L.PRODUCT_NO = P.NO,
        L.PURCHASE_QUANTITY = @PURCHASE_QUANTITY,
        L.ACCOUNT = @ACCOUNT,
        L.TOTAL_FEE = ROUND(P.PRICE * @PURCHASE_QUANTITY * P.FEE_RATE, 2),
        L.TOTAL_AMOUNT = ROUND(P.PRICE * @PURCHASE_QUANTITY * (1 + P.FEE_RATE), 2)
    FROM FAVORITE.LIKE_LIST L
    JOIN FINANCIAL.PRODUCT OLD_P ON OLD_P.NO = L.PRODUCT_NO
    JOIN FINANCIAL.PRODUCT P ON P.NO = @PRODUCT_NO
    WHERE L.SN = @SN
      AND OLD_P.USER_ID = @USER_ID
      AND P.USER_ID = @USER_ID;
    IF @@ROWCOUNT = 0
        THROW 50024, N'找不到喜好紀錄', 1;
END;
GO
-- 用途：依會員及喜好紀錄 SN 刪除資料。
CREATE OR ALTER PROCEDURE FAVORITE.DELETE_LIKE
    @SN INT,
    @USER_ID CHAR(10)
AS
BEGIN
    SET NOCOUNT ON;
    DELETE L
    FROM FAVORITE.LIKE_LIST L
    JOIN FINANCIAL.PRODUCT P ON P.NO = L.PRODUCT_NO
    WHERE L.SN = @SN
      AND P.USER_ID = @USER_ID;
    IF @@ROWCOUNT = 0
        THROW 50024, N'找不到喜好紀錄', 1;
END;
GO
