-- 二、TABLE
CREATE TABLE MEMBER.USER_ACCOUNT (
    USER_ID        CHAR(10)      NOT NULL,
    USER_NAME      NVARCHAR(10)  NOT NULL,
    EMAIL          VARCHAR(255)  NOT NULL,
    ACCOUNT        VARCHAR(20)   NOT NULL,
    PASSWORD_HASH  VARCHAR(60)   NOT NULL,
    CONSTRAINT PK_USER_ACCOUNT
        PRIMARY KEY (USER_ID)
);
GO
CREATE TABLE FINANCIAL.PRODUCT (
    NO            INT IDENTITY(1,1) NOT NULL,
    USER_ID       CHAR(10)          NOT NULL,
    PRODUCT_NAME  NVARCHAR(50)      NOT NULL,
    PRICE         DECIMAL(12,2)     NOT NULL,
    FEE_RATE      DECIMAL(10,6)     NOT NULL,
    CONSTRAINT PK_PRODUCT
        PRIMARY KEY (NO),
    CONSTRAINT FK_PRODUCT_USER
        FOREIGN KEY (USER_ID)
        REFERENCES MEMBER.USER_ACCOUNT(USER_ID),
    CONSTRAINT UK_PRODUCT_USER_NAME
        UNIQUE (USER_ID, PRODUCT_NAME)
);
GO
CREATE TABLE FAVORITE.LIKE_LIST (
    SN                 INT IDENTITY(1,1) NOT NULL,
    PRODUCT_NO         INT               NOT NULL,
    PURCHASE_QUANTITY  INT               NOT NULL,
    ACCOUNT            VARCHAR(20)       NOT NULL,
    TOTAL_FEE          DECIMAL(12,2)     NOT NULL,
    TOTAL_AMOUNT       DECIMAL(14,2)     NOT NULL,
    CONSTRAINT PK_LIKE_LIST
        PRIMARY KEY (SN),
    CONSTRAINT FK_LIKE_LIST_PRODUCT
        FOREIGN KEY (PRODUCT_NO)
        REFERENCES FINANCIAL.PRODUCT(NO),
    CONSTRAINT UK_LIKE_LIST_PRODUCT
        UNIQUE (PRODUCT_NO)
);
GO
-- 三、PROCEDURES
-- 3-1 MEMBER（會員相關，共 6 支）
-- 用途：檢查身分證字號是否已註冊
CREATE OR ALTER PROCEDURE MEMBER.CHECK_USER_ID
    @USER_ID CHAR(10),
    @EXISTS BIT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1
        FROM MEMBER.USER_ACCOUNT
        WHERE USER_ID = @USER_ID
    )
        SET @EXISTS = 1;
    ELSE
        SET @EXISTS = 0;
END;
GO
-- 用途：檢查 Email 是否重複；
CREATE OR ALTER PROCEDURE MEMBER.CHECK_EMAIL
    @EMAIL VARCHAR(255),
    @EXCLUDE_USER_ID CHAR(10) = NULL,
    @EXISTS BIT OUTPUT
AS
BEGIN
    SET NOCOUNT ON;
    IF EXISTS (
        SELECT 1
        FROM MEMBER.USER_ACCOUNT
        WHERE EMAIL = @EMAIL
          AND (
              @EXCLUDE_USER_ID IS NULL
              OR USER_ID <> @EXCLUDE_USER_ID
          )
    )
        SET @EXISTS = 1;
    ELSE
        SET @EXISTS = 0;
END;
GO
